package build.hands.update.internal

import com.google.archivepatcher.shared.IDeflater

/**
 * JNI entry points into the stock zlib 1.3.1 deflate compiled into
 * `libhandscrash.so` (see `src/main/cpp/hands_zlib_deflater.c`).
 */
internal object BundledZlib {
    /** True once the native library is loaded; false if it cannot be. Never throws. */
    val isAvailable: Boolean by lazy {
        try {
            System.loadLibrary("handscrash")
            nativeZlibVersion().isNotEmpty()
        } catch (_: Throwable) {
            false
        }
    }

    @JvmStatic external fun nativeInit(level: Int, strategy: Int, nowrap: Boolean): Long
    @JvmStatic external fun nativeSetDictionary(addr: Long, dictionary: ByteArray, off: Int, len: Int)
    @JvmStatic external fun nativeDeflate(
        addr: Long,
        input: ByteArray?,
        inputOff: Int,
        inputLen: Int,
        output: ByteArray,
        outputOff: Int,
        outputLen: Int,
        flush: Int,
        params: Int,
    ): Long
    @JvmStatic external fun nativeGetAdler(addr: Long): Int
    @JvmStatic external fun nativeReset(addr: Long)
    @JvmStatic external fun nativeEnd(addr: Long)
    @JvmStatic external fun nativeZlibVersion(): String
}

/**
 * An [IDeflater] that behaves exactly like `java.util.zip.Deflater` (as
 * archive-patcher's `DefaultDeflater` drives it) but compresses with the stock
 * zlib bundled in the SDK instead of the device's libz.
 *
 * Delta patches are generated by a JVM on stock zlib, and file-by-file patches
 * only rebuild the target APK when the device recompresses every entry
 * byte-for-byte the same way. Android 12+ ships Chromium's zlib fork, whose
 * deflate output differs, so the platform Deflater cannot be used.
 *
 * The state machine mirrors OpenJDK 17 `java.util.zip.Deflater`: level and
 * strategy changes are applied lazily through `deflateParams` on the next
 * [deflate] call, [finish] turns every later call into `Z_FINISH`, and
 * [reset] keeps the level and strategy.
 *
 * The constructor throws if the native library is unavailable; it never falls
 * back to the platform Deflater.
 */
internal class BundledZlibDeflater(level: Int, nowrap: Boolean) : IDeflater {
    private val lock = Any()
    private var address: Long
    private var inputArray: ByteArray? = null
    private var inputPos = 0
    private var inputLim = 0
    private var level = level
    private var strategy = DEFAULT_STRATEGY
    private var setParams = false
    private var finish = false
    private var finished = false
    private var bytesRead = 0L
    private var bytesWritten = 0L

    init {
        if (!BundledZlib.isAvailable) {
            throw UnsatisfiedLinkError("bundled zlib is not available")
        }
        address = BundledZlib.nativeInit(level, DEFAULT_STRATEGY, nowrap)
    }

    override fun setInput(input: ByteArray, off: Int, len: Int) {
        checkFromIndexSize(off, len, input.size)
        synchronized(lock) {
            inputArray = input
            inputPos = off
            inputLim = off + len
        }
    }

    override fun setInput(input: ByteArray) = setInput(input, 0, input.size)

    override fun setDictionary(dictionary: ByteArray, off: Int, len: Int) {
        checkFromIndexSize(off, len, dictionary.size)
        synchronized(lock) {
            BundledZlib.nativeSetDictionary(ensureOpen(), dictionary, off, len)
        }
    }

    override fun setDictionary(dictionary: ByteArray) = setDictionary(dictionary, 0, dictionary.size)

    override fun setStrategy(strategy: Int) {
        when (strategy) {
            DEFAULT_STRATEGY, FILTERED, HUFFMAN_ONLY -> Unit
            else -> throw IllegalArgumentException()
        }
        synchronized(lock) {
            if (this.strategy != strategy) {
                this.strategy = strategy
                setParams = true
            }
        }
    }

    override fun setLevel(level: Int) {
        if ((level < 0 || level > 9) && level != DEFAULT_COMPRESSION) {
            throw IllegalArgumentException("invalid compression level")
        }
        synchronized(lock) {
            if (this.level != level) {
                this.level = level
                setParams = true
            }
        }
    }

    override fun needsInput(): Boolean = synchronized(lock) { inputLim == inputPos }

    override fun finish() {
        synchronized(lock) { finish = true }
    }

    override fun finished(): Boolean = synchronized(lock) { finished }

    override fun deflate(output: ByteArray, off: Int, len: Int): Int =
        deflate(output, off, len, NO_FLUSH)

    override fun deflate(output: ByteArray): Int = deflate(output, 0, output.size, NO_FLUSH)

    override fun deflate(output: ByteArray, off: Int, len: Int, flush: Int): Int {
        checkFromIndexSize(off, len, output.size)
        if (flush != NO_FLUSH && flush != SYNC_FLUSH && flush != FULL_FLUSH) {
            throw IllegalArgumentException()
        }
        synchronized(lock) {
            val addr = ensureOpen()
            // As in the JDK: once finish() was called the given flush mode is disregarded.
            val mode = if (finish) FINISH else flush
            val params = if (setParams) 1 or (strategy shl 1) or (level shl 3) else 0
            val pos = inputPos
            val result = BundledZlib.nativeDeflate(
                addr, inputArray, pos, inputLim - pos, output, off, len, mode, params,
            )
            val read = (result and 0x7fff_ffffL).toInt()
            val written = ((result ushr 31) and 0x7fff_ffffL).toInt()
            if ((result ushr 62) and 1L != 0L) finished = true
            if (params != 0 && (result ushr 63) and 1L == 0L) setParams = false
            inputPos = pos + read
            bytesWritten += written
            bytesRead += read
            return written
        }
    }

    override fun getAdler(): Int = synchronized(lock) { BundledZlib.nativeGetAdler(ensureOpen()) }

    override fun getTotalIn(): Int = getBytesRead().toInt()

    override fun getBytesRead(): Long = synchronized(lock) {
        ensureOpen()
        bytesRead
    }

    override fun getTotalOut(): Int = getBytesWritten().toInt()

    override fun getBytesWritten(): Long = synchronized(lock) {
        ensureOpen()
        bytesWritten
    }

    override fun reset() {
        synchronized(lock) {
            BundledZlib.nativeReset(ensureOpen())
            finish = false
            finished = false
            inputArray = null
            inputPos = 0
            inputLim = 0
            bytesRead = 0
            bytesWritten = 0
        }
    }

    override fun end() {
        synchronized(lock) {
            val addr = address
            if (addr != 0L) {
                address = 0L
                inputArray = null
                BundledZlib.nativeEnd(addr)
            }
        }
    }

    /** Safety net for callers that drop a deflater without [end]; frees the native stream. */
    protected fun finalize() {
        try {
            end()
        } catch (_: Throwable) {
        }
    }

    private fun ensureOpen(): Long {
        val addr = address
        if (addr == 0L) throw NullPointerException("Deflater has been closed")
        return addr
    }

    companion object {
        // Same values as java.util.zip.Deflater and zlib.
        const val DEFAULT_COMPRESSION = -1
        const val DEFAULT_STRATEGY = 0
        const val FILTERED = 1
        const val HUFFMAN_ONLY = 2
        const val NO_FLUSH = 0
        const val SYNC_FLUSH = 2
        const val FULL_FLUSH = 3
        private const val FINISH = 4

        private fun checkFromIndexSize(off: Int, len: Int, size: Int) {
            if (off < 0 || len < 0 || off > size - len) {
                throw ArrayIndexOutOfBoundsException("Range [$off, $off + $len) out of bounds for length $size")
            }
        }
    }
}
