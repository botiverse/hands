package build.hands.desktop

import java.nio.file.Files
import java.nio.file.Path
import java.nio.file.attribute.PosixFilePermissions

/** How the helper starts the app after a swap. */
internal enum class RelaunchMode {
    /** `open -n <bundle> --args …` (macOS LaunchServices). */
    OPEN,
    /** Run the launcher executable directly. */
    EXEC,
}

/** The helper's waits. Defaults for real use; tests shorten them. */
internal data class SwapTimeouts(
    val appExitMillis: Long = 120_000,
    val launchConfirmMillis: Long = 60_000,
    val killGraceMillis: Long = 3_000,
    val tickMillis: Long = 100,
)

/**
 * Writes and starts the POSIX sh helper that swaps the staged tree in after the app exits.
 * Everything it needs is baked into the script, so its own command line names no install
 * path (a `pkill -f` for the app's executable path must not match the helper).
 */
internal object SwapHelper {
    const val SCRIPT = "hands-swap.sh"

    data class Spec(
        val appPid: Long,
        val installRoot: Path,
        val stagedRoot: Path,
        val stagingDir: Path,
        val backupDir: Path,
        val backup: Path,
        val failedDir: Path,
        val marker: Path,
        val lock: Path,
        val result: Path,
        val log: Path,
        val newVersionCode: Long,
        val mode: RelaunchMode,
        /** Absolute launcher path inside [installRoot] (EXEC). */
        val launcher: Path?,
        val relaunchArgs: List<String>,
        val timeouts: SwapTimeouts,
    )

    fun write(spec: Spec, script: Path) {
        val t = spec.timeouts
        val ticks = { ms: Long -> maxOf(1L, ms / t.tickMillis) }
        val tick = "%d.%03d".format(t.tickMillis / 1000, t.tickMillis % 1000)
        val killPattern = Regex("[.\\[\\]{}()*+?^$|\\\\]").replace("${spec.installRoot}/Contents/MacOS/") { "\\" + it.value }
        val text = buildString {
            appendLine("#!/bin/sh")
            appendLine("# Hands desktop swap helper, generated by build.hands:hands-desktop-updater.")
            appendLine("APP_PID=${spec.appPid}")
            appendLine("INSTALL_ROOT=${q(spec.installRoot)}")
            appendLine("STAGED_ROOT=${q(spec.stagedRoot)}")
            appendLine("STAGING_DIR=${q(spec.stagingDir)}")
            appendLine("BACKUP_DIR=${q(spec.backupDir)}")
            appendLine("BACKUP=${q(spec.backup)}")
            appendLine("FAILED=${q(spec.failedDir)}")
            appendLine("MARKER=${q(spec.marker)}")
            appendLine("LOCK=${q(spec.lock)}")
            appendLine("RESULT=${q(spec.result)}")
            appendLine("LOG=${q(spec.log)}")
            appendLine("NEW_CODE=${spec.newVersionCode}")
            appendLine("MODE=${if (spec.mode == RelaunchMode.OPEN) "open" else "exec"}")
            appendLine("LAUNCHER=${q(spec.launcher?.toString() ?: "")}")
            appendLine("KILL_PATTERN=${q(killPattern)}")
            appendLine("EXIT_TICKS=${ticks(t.appExitMillis)}")
            appendLine("LAUNCH_TICKS=${ticks(t.launchConfirmMillis)}")
            appendLine("KILL_TICKS=${ticks(t.killGraceMillis)}")
            appendLine("TICK=$tick")
            appendLine("set -- ${spec.relaunchArgs.joinToString(" ") { q(it) }}")
            append(BODY)
        }
        Files.createDirectories(script.parent)
        Files.writeString(script, text)
        Files.setPosixFilePermissions(script, PosixFilePermissions.fromString("rwx------"))
    }

    /** Start the helper so that it outlives this JVM: the intermediate sh exits at once. */
    fun launch(script: Path) {
        val process = ProcessBuilder(
            "/bin/sh", "-c", "nohup /bin/sh \"\$1\" </dev/null >/dev/null 2>&1 &", "hands-swap", script.toString(),
        ).redirectErrorStream(true).redirectOutput(ProcessBuilder.Redirect.DISCARD).start()
        val code = process.waitFor()
        if (code != 0) throw HandsUpdateException("could not start the swap helper (sh exited $code)")
    }

    private fun q(value: Any): String = "'" + value.toString().replace("'", "'\\''") + "'"

    private val BODY = """
trap '' HUP INT
exec >>"${'$'}LOG" 2>&1
log() { echo "${'$'}(date '+%Y-%m-%dT%H:%M:%S') hands-swap[${'$'}${'$'}]: ${'$'}*"; }
finish() {
  echo "${'$'}1 ${'$'}NEW_CODE" > "${'$'}RESULT.tmp" && mv -f "${'$'}RESULT.tmp" "${'$'}RESULT"
  rm -f "${'$'}LOCK"
  log "${'$'}1"
  exit 0
}
alive() {
  s=${'$'}(ps -o stat= -p "${'$'}1" 2>/dev/null) || return 1
  case "${'$'}s" in *Z*|"") return 1 ;; esac
  return 0
}
NEW_PID=
launch() {
  if [ "${'$'}MODE" = open ]; then
    if [ ${'$'}# -gt 0 ]; then open -n "${'$'}INSTALL_ROOT" --args "${'$'}@"; else open -n "${'$'}INSTALL_ROOT"; fi
  else
    "${'$'}LAUNCHER" "${'$'}@" </dev/null >/dev/null 2>&1 &
    NEW_PID=${'$'}!
  fi
}
stop_new() {
  if [ "${'$'}MODE" = open ]; then
    pkill -TERM -f "${'$'}KILL_PATTERN" 2>/dev/null
    n=0; while pgrep -f "${'$'}KILL_PATTERN" >/dev/null 2>&1 && [ ${'$'}n -lt ${'$'}KILL_TICKS ]; do n=${'$'}((n+1)); sleep ${'$'}TICK; done
    pkill -KILL -f "${'$'}KILL_PATTERN" 2>/dev/null
  elif [ -n "${'$'}NEW_PID" ]; then
    kill -TERM "${'$'}NEW_PID" 2>/dev/null
    n=0; while alive "${'$'}NEW_PID" && [ ${'$'}n -lt ${'$'}KILL_TICKS ]; do n=${'$'}((n+1)); sleep ${'$'}TICK; done
    kill -KILL "${'$'}NEW_PID" 2>/dev/null
    wait "${'$'}NEW_PID" 2>/dev/null
  fi
}
restore() {
  rm -rf "${'$'}FAILED"
  if [ -e "${'$'}INSTALL_ROOT" ] || [ -L "${'$'}INSTALL_ROOT" ]; then
    mv "${'$'}INSTALL_ROOT" "${'$'}FAILED" || rm -rf "${'$'}INSTALL_ROOT"
  fi
  if ! mv "${'$'}BACKUP" "${'$'}INSTALL_ROOT"; then
    log "FATAL: could not restore ${'$'}BACKUP to ${'$'}INSTALL_ROOT"
    return 1
  fi
  rm -rf "${'$'}FAILED"
  return 0
}

echo ${'$'}${'$'} > "${'$'}LOCK"
log "waiting for app ${'$'}APP_PID to exit"
n=0
while kill -0 "${'$'}APP_PID" 2>/dev/null; do
  n=${'$'}((n+1))
  if [ ${'$'}n -gt ${'$'}EXIT_TICKS ]; then log "app ${'$'}APP_PID did not exit in time"; finish aborted; fi
  sleep ${'$'}TICK
done

rm -f "${'$'}MARKER"
mkdir -p "${'$'}BACKUP_DIR"
rm -rf "${'$'}BACKUP"
# mv is a rename on one filesystem and a copy plus delete across filesystems.
if ! mv "${'$'}INSTALL_ROOT" "${'$'}BACKUP"; then
  log "could not move ${'$'}INSTALL_ROOT aside"
  if [ ! -e "${'$'}INSTALL_ROOT" ] && [ -e "${'$'}BACKUP" ]; then mv "${'$'}BACKUP" "${'$'}INSTALL_ROOT"; fi
  launch "${'$'}@"
  finish aborted
fi
if ! mv "${'$'}STAGED_ROOT" "${'$'}INSTALL_ROOT"; then
  log "could not move the new tree into place"
  restore
  launch "${'$'}@"
  finish aborted
fi
log "swapped in version ${'$'}NEW_CODE; relaunching"
launch "${'$'}@"

n=0
while :; do
  if [ "${'$'}(cat "${'$'}MARKER" 2>/dev/null)" = "${'$'}NEW_CODE" ]; then break; fi
  n=${'$'}((n+1))
  # A launcher that exits early is not a failure by itself (it may hand off to another
  # process); only the missing confirmation is.
  if [ ${'$'}n -gt ${'$'}LAUNCH_TICKS ]; then
    # One last look: the app may have confirmed just now.
    if [ "${'$'}(cat "${'$'}MARKER" 2>/dev/null)" = "${'$'}NEW_CODE" ]; then break; fi
    log "version ${'$'}NEW_CODE did not confirm its launch; rolling back"
    stop_new
    if restore; then
      rm -f "${'$'}MARKER"
      launch "${'$'}@"
    fi
    rm -rf "${'$'}STAGING_DIR"
    finish rolled-back
  fi
  sleep ${'$'}TICK
done

rm -rf "${'$'}STAGING_DIR"
for d in "${'$'}BACKUP_DIR"/* "${'$'}BACKUP_DIR"/.[!.]*; do
  [ -e "${'$'}d" ] || [ -L "${'$'}d" ] || continue
  [ "${'$'}d" = "${'$'}BACKUP" ] || rm -rf "${'$'}d"
done
finish installed
""".trimStart()
}
