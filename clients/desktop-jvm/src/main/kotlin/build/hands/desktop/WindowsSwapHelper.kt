package build.hands.desktop

import java.nio.file.Files
import java.nio.file.Path

/**
 * The Windows counterpart of [SwapHelper]: a PowerShell script (Windows PowerShell 5.1 ships
 * with every supported Windows) that waits for the app to exit, swaps the staged tree in,
 * relaunches it, and rolls back when the new version does not confirm its launch.
 *
 * Differences from the sh helper:
 * - Windows refuses to rename a directory while any process holds a file in it open (an
 *   antivirus scan, the indexer, a crash reporter), so each move is retried for a while,
 *   and a move across volumes falls back to copy plus delete.
 * - There is no LaunchServices: the launcher is always started directly.
 * - Stopping the new version is `CloseMainWindow`, then a forced stop after the grace time.
 */
internal object WindowsSwapHelper {
    const val SCRIPT = "hands-swap.ps1"

    /** How long a rename keeps being retried while something holds a file open. */
    internal const val MOVE_RETRY_MILLIS = 15_000L

    fun write(spec: SwapHelper.Spec, script: Path) {
        val t = spec.timeouts
        val launcher = spec.launcher ?: throw HandsUpdateException("a launcher is required on Windows")
        val text = buildString {
            appendLine("# Hands desktop swap helper, generated by build.hands:hands-desktop-updater.")
            appendLine("\$AppPid = ${spec.appPid}")
            appendLine("\$InstallRoot = ${q(spec.installRoot)}")
            appendLine("\$StagedRoot = ${q(spec.stagedRoot)}")
            appendLine("\$StagingDir = ${q(spec.stagingDir)}")
            appendLine("\$BackupDir = ${q(spec.backupDir)}")
            appendLine("\$Backup = ${q(spec.backup)}")
            appendLine("\$Failed = ${q(spec.failedDir)}")
            appendLine("\$Marker = ${q(spec.marker)}")
            appendLine("\$Lock = ${q(spec.lock)}")
            appendLine("\$Result = ${q(spec.result)}")
            appendLine("\$Log = ${q(spec.log)}")
            appendLine("\$NewCode = '${spec.newVersionCode}'")
            appendLine("\$Launcher = ${q(launcher)}")
            appendLine("\$ArgLine = ${q(commandLine(spec.relaunchArgs))}")
            appendLine("\$ExitMillis = ${t.appExitMillis}")
            appendLine("\$LaunchMillis = ${t.launchConfirmMillis}")
            appendLine("\$KillMillis = ${t.killGraceMillis}")
            appendLine("\$TickMillis = ${t.tickMillis}")
            appendLine("\$MoveMillis = ${minOf(MOVE_RETRY_MILLIS, maxOf(t.tickMillis * 10, t.appExitMillis))}")
            append(BODY)
        }
        Files.createDirectories(script.parent)
        // A byte order mark makes Windows PowerShell 5.1 read the script as UTF-8, so paths
        // outside the ANSI code page survive.
        Files.write(script, byteArrayOf(0xEF.toByte(), 0xBB.toByte(), 0xBF.toByte()) + text.toByteArray(Charsets.UTF_8))
    }

    /** Start the helper detached; on Windows a child outlives the JVM that started it. */
    fun launch(script: Path) {
        val root = System.getenv("SystemRoot") ?: "C:\\Windows"
        val powershell = Path.of(root, "System32", "WindowsPowerShell", "v1.0", "powershell.exe")
        val exe = if (Files.isRegularFile(powershell)) powershell.toString() else "powershell.exe"
        try {
            ProcessBuilder(exe, "-NoProfile", "-NonInteractive", "-ExecutionPolicy", "Bypass", "-WindowStyle", "Hidden",
                "-File", script.toString())
                .redirectErrorStream(true)
                .redirectOutput(ProcessBuilder.Redirect.DISCARD)
                .redirectInput(ProcessBuilder.Redirect.from(java.io.File("NUL")))
                .start()
        } catch (e: java.io.IOException) {
            throw HandsUpdateException("could not start the swap helper: ${e.message}", e)
        }
    }

    /** A PowerShell single-quoted literal. */
    private fun q(value: Any): String = "'" + value.toString().replace("'", "''") + "'"

    /**
     * One Windows command line from [args], quoted the way the Microsoft C runtime splits it
     * (CommandLineToArgvW): an argument with spaces, tabs or quotes goes in quotes, a quote is
     * escaped with a backslash, and backslashes before a quote are doubled.
     */
    internal fun commandLine(args: List<String>): String = args.joinToString(" ") { arg ->
        if (arg.isNotEmpty() && arg.none { it == ' ' || it == '\t' || it == '"' }) return@joinToString arg
        val out = StringBuilder("\"")
        var slashes = 0
        for (c in arg) {
            when (c) {
                '\\' -> slashes++
                '"' -> { out.append("\\".repeat(slashes * 2 + 1)).append('"'); slashes = 0 }
                else -> { out.append("\\".repeat(slashes)).append(c); slashes = 0 }
            }
        }
        out.append("\\".repeat(slashes * 2)).append('"').toString()
    }

    private val BODY = """
${'$'}ErrorActionPreference = 'Continue'
function Log([string]${'$'}m) {
  Add-Content -LiteralPath ${'$'}Log -Value ("{0} hands-swap[{1}]: {2}" -f (Get-Date -Format 'yyyy-MM-ddTHH:mm:ss'), ${'$'}PID, ${'$'}m)
}
function Finish([string]${'$'}outcome) {
  Set-Content -LiteralPath "${'$'}Result.tmp" -Value "${'$'}outcome ${'$'}NewCode" -NoNewline
  Move-Item -LiteralPath "${'$'}Result.tmp" -Destination ${'$'}Result -Force
  Remove-Item -LiteralPath ${'$'}Lock -Force -ErrorAction SilentlyContinue
  Log ${'$'}outcome
  exit 0
}
function Alive([int]${'$'}p) { ${'$'}null -ne (Get-Process -Id ${'$'}p -ErrorAction SilentlyContinue) }
function Exists([string]${'$'}p) { Test-Path -LiteralPath ${'$'}p }
# Rename, retried while something holds a file open; across volumes, copy then delete.
function MoveDir([string]${'$'}from, [string]${'$'}to) {
  ${'$'}deadline = (Get-Date).AddMilliseconds(${'$'}MoveMillis)
  while (${'$'}true) {
    try { [System.IO.Directory]::Move(${'$'}from, ${'$'}to); return ${'$'}true } catch { ${'$'}err = ${'$'}_.Exception.Message }
    if ((Get-Date) -gt ${'$'}deadline) { break }
    Start-Sleep -Milliseconds ${'$'}TickMillis
  }
  if ([System.IO.Path]::GetPathRoot(${'$'}from) -ne [System.IO.Path]::GetPathRoot(${'$'}to)) {
    try {
      Copy-Item -LiteralPath ${'$'}from -Destination ${'$'}to -Recurse -Force -ErrorAction Stop
      Remove-Item -LiteralPath ${'$'}from -Recurse -Force -ErrorAction Stop
      return ${'$'}true
    } catch { ${'$'}err = ${'$'}_.Exception.Message }
  }
  Log "move ${'$'}from -> ${'$'}to failed: ${'$'}err"
  return ${'$'}false
}
${'$'}NewProc = ${'$'}null
function Launch {
  try {
    if (${'$'}ArgLine -ne '') {
      ${'$'}script:NewProc = Start-Process -FilePath ${'$'}Launcher -ArgumentList ${'$'}ArgLine -WorkingDirectory ${'$'}InstallRoot -PassThru
    } else {
      ${'$'}script:NewProc = Start-Process -FilePath ${'$'}Launcher -WorkingDirectory ${'$'}InstallRoot -PassThru
    }
  } catch { Log ("could not start {0}: {1}" -f ${'$'}Launcher, ${'$'}_.Exception.Message) }
}
# The new version and everything it started: a child left running would keep files in the
# install open, and Windows would then refuse to move the install back.
function StopNew {
  if (${'$'}null -eq ${'$'}script:NewProc) { return }
  try { [void]${'$'}script:NewProc.CloseMainWindow() } catch {}
  if (-not ${'$'}script:NewProc.WaitForExit([int]${'$'}KillMillis)) {
    & taskkill.exe /PID ${'$'}script:NewProc.Id /T /F 2>&1 | Out-Null
    [void]${'$'}script:NewProc.WaitForExit(5000)
  } else {
    & taskkill.exe /PID ${'$'}script:NewProc.Id /T /F 2>&1 | Out-Null
  }
}
function Restore {
  Remove-Item -LiteralPath ${'$'}Failed -Recurse -Force -ErrorAction SilentlyContinue
  if (Exists ${'$'}InstallRoot) {
    if (-not (MoveDir ${'$'}InstallRoot ${'$'}Failed)) { Remove-Item -LiteralPath ${'$'}InstallRoot -Recurse -Force -ErrorAction SilentlyContinue }
  }
  if (-not (MoveDir ${'$'}Backup ${'$'}InstallRoot)) {
    Log "FATAL: could not restore ${'$'}Backup to ${'$'}InstallRoot"
    return ${'$'}false
  }
  Remove-Item -LiteralPath ${'$'}Failed -Recurse -Force -ErrorAction SilentlyContinue
  return ${'$'}true
}
function MarkerSays { ((Get-Content -LiteralPath ${'$'}Marker -Raw -ErrorAction SilentlyContinue) -as [string]).Trim() -eq ${'$'}NewCode }

Set-Content -LiteralPath ${'$'}Lock -Value ${'$'}PID -NoNewline
Log "waiting for app ${'$'}AppPid to exit"
${'$'}deadline = (Get-Date).AddMilliseconds(${'$'}ExitMillis)
while (Alive ${'$'}AppPid) {
  if ((Get-Date) -gt ${'$'}deadline) { Log "app ${'$'}AppPid did not exit in time"; Finish 'aborted' }
  Start-Sleep -Milliseconds ${'$'}TickMillis
}

Remove-Item -LiteralPath ${'$'}Marker -Force -ErrorAction SilentlyContinue
New-Item -ItemType Directory -Force -Path ${'$'}BackupDir | Out-Null
Remove-Item -LiteralPath ${'$'}Backup -Recurse -Force -ErrorAction SilentlyContinue
if (-not (MoveDir ${'$'}InstallRoot ${'$'}Backup)) {
  Log "could not move ${'$'}InstallRoot aside"
  if (-not (Exists ${'$'}InstallRoot) -and (Exists ${'$'}Backup)) { [void](MoveDir ${'$'}Backup ${'$'}InstallRoot) }
  Launch
  Finish 'aborted'
}
if (-not (MoveDir ${'$'}StagedRoot ${'$'}InstallRoot)) {
  Log "could not move the new tree into place"
  [void](Restore)
  Launch
  Finish 'aborted'
}
Log "swapped in version ${'$'}NewCode; relaunching"
Launch

${'$'}deadline = (Get-Date).AddMilliseconds(${'$'}LaunchMillis)
while (-not (MarkerSays)) {
  # A launcher that exits early is not a failure by itself (it may hand off to another
  # process); only the missing confirmation is.
  if ((Get-Date) -gt ${'$'}deadline) {
    if (MarkerSays) { break }
    Log "version ${'$'}NewCode did not confirm its launch; rolling back"
    StopNew
    if (Restore) {
      Remove-Item -LiteralPath ${'$'}Marker -Force -ErrorAction SilentlyContinue
      Launch
    }
    Remove-Item -LiteralPath ${'$'}StagingDir -Recurse -Force -ErrorAction SilentlyContinue
    Finish 'rolled-back'
  }
  Start-Sleep -Milliseconds ${'$'}TickMillis
}

Remove-Item -LiteralPath ${'$'}StagingDir -Recurse -Force -ErrorAction SilentlyContinue
Get-ChildItem -LiteralPath ${'$'}BackupDir -Force -ErrorAction SilentlyContinue |
  Where-Object { ${'$'}_.FullName -ne ${'$'}Backup } |
  ForEach-Object { Remove-Item -LiteralPath ${'$'}_.FullName -Recurse -Force -ErrorAction SilentlyContinue }
Finish 'installed'
""".trimStart()
}
